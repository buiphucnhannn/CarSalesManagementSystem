package vn.edu.ute.carsalesms.model.enums;

/**
 * Enum định nghĩa các giá trị cho giới tính.
 * Sử dụng enum giúp đảm bảo tính nhất quán và hạn chế các giá trị không hợp lệ.
 */
public enum Gender {
    /**
     * Giới tính Nam.
     */
    MALE,
    /**
     * Giới tính Nữ.
     */
    FEMALE,
    /**
     * Giới tính khác.
     */
    OTHER
}
